import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(root, 'src/chatgpt-app/dist');
const cssPath = path.join(distDir, 'widget.css');
const outTs = path.join(root, 'api/mcp/generated-widget-bundle.ts');

await mkdir(distDir, { recursive: true });

const tailwind = spawnSync(
  process.execPath,
  [
    path.join(root, 'node_modules/tailwindcss/lib/cli.js'),
    '--config',
    path.join(root, 'tailwind.config.mjs'),
    '--input',
    path.join(root, 'src/chatgpt-app/widgets/input.css'),
    '--output',
    cssPath,
    '--minify',
  ],
  { cwd: root, stdio: 'inherit' },
);
if (tailwind.status !== 0) {
  process.exit(tailwind.status ?? 1);
}

const extraCss = await readFile(path.join(root, 'src/components/sunny/sunny-generative.css'), 'utf8');
const utilities = await readFile(cssPath, 'utf8');
const css = `${utilities}\n${extraCss}`;

const bundle = await esbuild.build({
  absWorkingDir: root,
  entryPoints: [path.join(root, 'src/chatgpt-app/widgets/entry.tsx')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  jsx: 'automatic',
  write: false,
  minify: true,
  logLevel: 'warning',
  alias: {
    'react-router-dom': path.join(root, 'src/chatgpt-app/widgets/link-shim.tsx'),
  },
  loader: {
    '.css': 'empty',
  },
});

const script = bundle.outputFiles[0]?.text ?? '';
const source = `/** Generated by scripts/build-chatgpt-widgets.mjs. Do not edit by hand. */\nexport const script = ${JSON.stringify(script)};\nexport const css = ${JSON.stringify(css)};\n`;
await writeFile(outTs, source);
await writeFile(path.join(distDir, 'widget.js'), script);
await writeFile(cssPath, css);
console.log('wrote', path.relative(root, outTs), `(js ${script.length} bytes, css ${css.length} bytes)`);
